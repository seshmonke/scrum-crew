#!/usr/bin/env bash
# slop-check.sh — ловит лексический и пунктуационный слоп в готовом тексте.
# Использование: bash .opencode/skills/scrum-crew/scripts/slop-check.sh <file> [file...]
# Скрипт не понимает смысл. Он ловит следы: штампы, канцелярит, давление.
set -euo pipefail

if [ "$#" -eq 0 ]; then
  printf 'Usage: bash .opencode/skills/scrum-crew/scripts/slop-check.sh <file> [file...]\n' >&2
  exit 2
fi

patterns='в современном мире|сегодня как никогда|не просто|это не .* — это|откройте для себя|погрузитесь|раскройте потенциал|выведите на новый уровень|уникальн|инновационн|революционн|премиальн|эксклюзивн|роскошн|элитн|идеальн|безупречн|широкий спектр|гибкие решения|комплексные решения|оптимизация процессов|команда профессионалов|многолетний опыт|лидер рынка|номер один|мы верим|наша миссия|мы создали|которому можно доверять|которой можно доверять|без компромиссов|знакомая картина|то, что действительно важно|общая память команды|для тех, кто|больше, чем|экосистем|синерги|бесшовн|кураторск|осознанн|аутентичн|глубок|мощн|прорывн|вдохновляющ|трансформационн|масштабирован|digital-трансформац|оставьте заявку|мы дорожим каждым|под ключ|в кратчайшие сроки|является|осуществляет|данный|в рамках|с целью'

status=0

for file in "$@"; do
  if [ ! -f "$file" ]; then
    printf 'skip: %s (not a file)\n' "$file" >&2
    continue
  fi

  hits="$(grep -nEi "$patterns" "$file" || true)"
  if [ -n "$hits" ]; then
    printf 'SLOP: %s\n' "$file"
    printf '%s\n' "$hits"
    status=1
  fi

  if grep -nE '(^|[^!])!([^[]|$)' "$file" >/dev/null 2>&1; then
    printf 'PUNCT: %s: восклицательный знак\n' "$file"
    status=1
  fi
done

if [ "$status" -eq 0 ]; then
  printf 'OK: slop not found\n'
fi

exit "$status"
